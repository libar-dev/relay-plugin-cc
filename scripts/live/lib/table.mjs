import fs from 'node:fs';
import path from 'node:path';
import { recordKeys } from './runs.mjs';

export const staleMessage = 'docs/live/capabilities.md is out of date: run node scripts/live/suite.mjs table';

export function readRecords(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith('.jsonl')).map(entry => entry.name).sort().flatMap(name => {
      const file = path.join(directory, name);
      return fs.readFileSync(file, 'utf8').split('\n').flatMap((line, i) => {
        if (!line.trim()) return [];
        let row;
        try { row = JSON.parse(line); }
        catch { throw new Error(`Invalid record at ${file}:${i + 1}: invalid JSON.`); }
        if (!row || recordKeys.some(key => !Object.hasOwn(row, key))) throw new Error(`Invalid record at ${file}:${i + 1}: missing record field.`);
        return [row];
      });
    });
}

const escapeCell = value => String(value ?? '—').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const row = cells => `| ${cells.map(escapeCell).join(' | ')} |`;
const finishTime = record => Number.isFinite(Date.parse(record.finishedAt)) ? Date.parse(record.finishedAt) : -Infinity;
const compare = (a, b) => finishTime(a) - finishTime(b) || a.runId.localeCompare(b.runId);

export function renderTable(records, registry, { BACKENDS, BACKEND_NAMES }, relayVersion) {
  const latest = new Map();
  for (const record of records) {
    const check = registry.find(item => item.id === record.check);
    if (!check?.surfaces.includes(record.surface) || !BACKENDS.includes(record.backend) ||
        (relayVersion !== undefined && record.relayVersion !== relayVersion)) continue;
    const key = `${record.check}/${record.surface}/${record.backend}`;
    if (!latest.has(key) || compare(record, latest.get(key)) > 0) latest.set(key, record);
  }
  const lines = [
    '# What the live suite has passed', '',
    '<!-- Generated by `node scripts/live/suite.mjs table` from docs/live/records/. Do not edit it by hand. -->', '',
    'Each cell is the latest record of a check on one backend and surface, shown only when it passed. A dash is a',
    'check that has not passed there: not run yet, or failed in its latest run. [scripts/live/](../../scripts/live/)',
    'holds the checks; the records below name the builds.', ''
  ];
  const shown = [];
  for (const [surface, title] of [['terminal', 'Terminal'], ['t3', 'T3 Code']]) {
    lines.push(`## ${title}`, '', row(['Check', ...BACKENDS.map(backend => BACKEND_NAMES[backend])]), '|---|---|---|---|---|');
    for (const check of registry.filter(item => item.surfaces.includes(surface))) {
      lines.push(row([check.title, ...BACKENDS.map(backend => {
        const record = latest.get(`${check.id}/${surface}/${backend}`);
        if (record?.result !== 'pass') return '—';
        shown.push(record);
        return check.cell(record);
      })]));
    }
    lines.push('');
  }
  lines.push('## How a backend takes a message sent while its turn runs', '',
    '- **Into the running turn**: Codex (`turn/steer`), Grok Build (`_x.ai/interject`) and ZCode (`sendText` with',
    '  `guide`) add the message to the turn that is running.',
    '- **As the next turn**: Kimi Code. ACP has no steer, and a running Kimi turn takes no message. The message',
    '  reaches the job as fast as on the other backends, waits for the running turn to end, and then runs as a turn of',
    '  its own; the running turn never sees it.',
    '- **A new turn on the same session**: a message sent after the job ended continues the backend session the job',
    '  ran in.', '', '## Records behind each cell', '',
    '| Check | Surface | Backend | Model | Relay | Claude Code | Lead | Date | Record |',
    '|---|---|---|---|---|---|---|---|---|');
  for (const record of shown) lines.push(row([record.check, record.surface, record.backend, record.model,
    record.relayVersion, record.claudeCodeVersion, record.leadModel, record.finishedAt?.slice(0, 10),
    `[${record.runId}](records/${record.runId}.jsonl)`]));
  return lines.join('\n') + '\n';
}

export function writeTable(options, registry, readers, warn = console.error) {
  const content = renderTable(readRecords(options.recordsDir), registry, readers, options.relayVersion);
  if (options.check) {
    if (!fs.existsSync(options.out) || fs.readFileSync(options.out, 'utf8') !== content) { warn(staleMessage); return 1; }
    return 0;
  }
  fs.mkdirSync(path.dirname(options.out), { recursive: true });
  fs.writeFileSync(options.out, content);
  return 0;
}
